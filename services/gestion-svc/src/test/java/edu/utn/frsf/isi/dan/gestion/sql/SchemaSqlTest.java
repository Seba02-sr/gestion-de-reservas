package edu.utn.frsf.isi.dan.gestion.sql;

import static org.junit.jupiter.api.Assertions.*;

import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;

/**
 * Chequeo estático del script de Postgres (el comportamiento real se verifica levantando una base;
 * ver CLAUDE.md): los tipos de habitación sembrados con id fijo no deben dejar la secuencia de la
 * identidad atrás, o el primer alta por la API chocaría con el id 1.
 */
class SchemaSqlTest {

  private static String sql() throws Exception {
    return Files.readString(Path.of("..", "..", "infra", "postgres", "initdb", "01_schema.sql"));
  }

  @Test
  void despuesDelSeedDeTiposDeHabitacionSeAjustaLaSecuenciaAlMayorId() throws Exception {
    String sql = sql();
    int seed = sql.indexOf("INSERT INTO tp_dan.tipo_habitacion");
    int setval = sql.indexOf("setval(pg_get_serial_sequence('tp_dan.tipo_habitacion', 'id')");

    assertTrue(seed >= 0, "falta el INSERT de tipos");
    assertTrue(setval > seed, "el setval tiene que ir después del INSERT con ids fijos");
    assertTrue(sql.contains("SELECT COALESCE(MAX(id), 1) FROM tp_dan.tipo_habitacion"));
  }

  @Test
  void elIdDeTipoHabitacionEsUnaIdentidadYLaFechaFinDeTarifaEsNullable() throws Exception {
    String sql = sql();

    assertTrue(sql.contains("id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
    assertTrue(sql.contains("fecha_fin date,"));
    assertTrue(sql.contains("ALTER COLUMN fecha_fin DROP NOT NULL"));
  }
}
